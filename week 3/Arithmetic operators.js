let num = 10;

console.log(num - "ahmed"); //! NaN = not a number
console.log(num + "Ahmed"); //* 10Ahmed >> concatination

//* Exponentiation >> ** الاس
console.log(10 ** 2); // 10^2 = 100

//* modulus >> %
console.log(10 % 2); // zero
console.log(11 % 2); // 1

//* increment >> ++ 
//* decrement >> --
console.log(num++); // 10 post increment
console.log(num); // 11 >> 10+1
console.log(++num); // 12 >> 1+11 pre increment
console.log(--num); // 11 >> 12-1 pre decrement
