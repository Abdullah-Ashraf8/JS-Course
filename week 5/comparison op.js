/*
  Comparison Operators
  - == Equal
  - != Not Equal

  - === Identical
  - !== Not Identical

  - > Larger Than
  - >= Larger Than Or Equal

  - < Smaller Than
  - <= Smaller Than Or Equal
*/

console.log(10 == "10"); // compare value only
console.log(10 != "10"); // compare value only

console.log(10 === "10"); // compare value and data type
console.log(10 === 10); // compare value and data type
console.log(10 !== "10"); // compare value and data type

console.log("10" !== "10"); // compare value and data type
console.log("ahmed" === "mohamed"); // compare value and data type
console.log(typeof "ahmed" === typeof "mohamed"); // compare value and data type